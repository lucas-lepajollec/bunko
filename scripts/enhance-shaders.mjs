// Turns bloc97's Anime4K mpv shaders (MIT, https://github.com/bloc97/Anime4K) into modules the
// player loads on demand: `node scripts/enhance-shaders.mjs <folder with the .glsl files>`.
// Each file is kept verbatim, licence header included; only the module wrapper is added.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const from = process.argv[2];
if (!from) throw new Error('usage: node scripts/enhance-shaders.mjs <folder>');
const out = new URL('../src/lib/client/enhance/shaders/', import.meta.url);
const name = (file) =>
  file
    .replace(/^Anime4K_/, 'a4k-')
    .replace(/\.glsl$/, '')
    .replace(/_CNN/, '')
    .replace(/_/g, '-')
    .toLowerCase();
for (const file of readdirSync(from).filter(
  (f) => f.startsWith('Anime4K_') && f.endsWith('.glsl'),
)) {
  const source = readFileSync(join(from, file), 'utf8');
  writeFileSync(
    new URL(`${name(file)}.ts`, out),
    `// ${file} from bloc97/Anime4K (MIT), generated by scripts/enhance-shaders.mjs.\n` +
      `export default ${JSON.stringify(source)};\n`,
  );
  console.log(name(file));
}
