/**
 * Interface translations. English is the reference: every language must define exactly the same
 * keys and placeholders (enforced by tests/i18n.test.ts). Titles and synopses come from providers
 * and keep their original language.
 */
export type UiLanguage = 'en' | 'fr' | 'es' | 'de' | 'it';

export const UI_LANGUAGES: { id: UiLanguage; label: string; locale: string }[] = [
  { id: 'en', label: 'English', locale: 'en-US' },
  { id: 'fr', label: 'Français', locale: 'fr-FR' },
  { id: 'es', label: 'Español', locale: 'es-ES' },
  { id: 'de', label: 'Deutsch', locale: 'de-DE' },
  { id: 'it', label: 'Italiano', locale: 'it-IT' },
];

export const BCP47 = Object.fromEntries(UI_LANGUAGES.map((l) => [l.id, l.locale])) as Record<
  UiLanguage,
  string
>;

export function isUiLanguage(value: string | null | undefined): value is UiLanguage {
  return UI_LANGUAGES.some((l) => l.id === value);
}

export function interpolate(template: string, variables?: Record<string, string | number>) {
  return variables
    ? template.replace(/\{(\w+)\}/g, (m, k: string) => (k in variables ? String(variables[k]) : m))
    : template;
}

